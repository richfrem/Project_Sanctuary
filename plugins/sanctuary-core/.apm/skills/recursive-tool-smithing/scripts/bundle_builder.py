from pathlib import Path
import argparse, json, sys
from typing import Any, Dict, List

def read_manifest(path: Path) -> Dict[str, Any]:
    """Load JSON manifest from path."""
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)

def make_bundle_text(manifest: Dict[str, Any], repo_root: Path) -> str:
    """Assemble markdown bundle text from manifest and repo root."""
    title = manifest.get("title", "Untitled")
    desc = manifest.get("description", "")
    parts: List[str] = [f"# {title}", "", desc, ""]
    for entry in manifest.get("files", []):
        p = entry.get("path", "")
        note = entry.get("note", "")
        parts.append(f"## {p}")
        if note:
            parts.append(f"*{note}*")
        fp = (repo_root / p).resolve()
        if fp.exists() and fp.is_file():
            try:
                text = fp.read_text(encoding="utf-8")
            except Exception as e:
                parts.append(f"`ERROR READING FILE: {e}`")
                parts.append("")
                continue
            parts.append("```")
            parts.append(text.rstrip("\n"))
            parts.append("```")
        else:
            parts.append("> NOT FOUND")
        parts.append("")  # spacer
    return "\n".join(parts).rstrip() + "\n"

def build_bundle(manifest_path: Path, output_path: Path, repo_root: Path) -> None:
    manifest = read_manifest(manifest_path)
    bundle = make_bundle_text(manifest, repo_root)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8") as f:
        f.write(bundle)

def self_test() -> None:
    """Print a sample bundle to stdout using this script file as example content."""
    repo_root = Path.cwd()
    sample = {
        "title": "Self-Test Bundle",
        "description": "Generated by bundle_builder self-test. Contains this script and a missing file.",
        "files": [
            {"path": Path(__file__).relative_to(repo_root).as_posix() if repo_root in Path(__file__).parents else Path(__file__).name, "note": "This script"},
            {"path": "nonexistent.txt", "note": "Should be missing"}
        ]
    }
    print(make_bundle_text(sample, repo_root))

def parse_args():
    p = argparse.ArgumentParser(description="Build context bundle from JSON manifest.")
    p.add_argument("--manifest", type=Path, help="Path to manifest JSON")
    p.add_argument("--output", type=Path, default=Path("/tmp/context_bundle.md"), help="Output markdown path")
    p.add_argument("--self-test", action="store_true", help="Run self-test and print to stdout (no files created)")
    return p.parse_args()

if __name__ == "__main__":
    args = parse_args()
    if args.self_test:
        self_test(); sys.exit(0)
    if not args.manifest:
        self_test(); sys.exit(0)
    try:
        build_bundle(args.manifest, args.output, Path.cwd())
    except Exception as e:
        print(f"Failed: {e}", file=sys.stderr); sys.exit(1)
    print(f"Wrote bundle to {args.output}")
