#!/usr/bin/env python3
"""
Unit tests for manage_backlog.py
"""

import json
import shutil
import tempfile
import unittest
from pathlib import Path

# Add script directory to sys.path
import sys
SCRIPT_DIR = Path(__file__).resolve().parents[1] / "scripts"
sys.path.insert(0, str(SCRIPT_DIR))

from manage_backlog import BacklogManager, calculate_priority_score


class TestBacklogManager(unittest.TestCase):
    def setUp(self):
        self.temp_dir = Path(tempfile.mkdtemp())
        self.mgr = BacklogManager(root_dir=self.temp_dir)

    def tearDown(self):
        shutil.rmtree(self.temp_dir)

    def test_priority_score_calculation(self):
        # 5 * 4 / (0.05 * 2) = 20 / 0.1 = 200.0
        score = calculate_priority_score(5, 4, 0.05, 2)
        self.assertEqual(score, 200.0)

        # 5 * 4 / (0.1 * 2) = 20 / 0.2 = 100.0
        score2 = calculate_priority_score(5, 4, 0.1, 2)
        self.assertEqual(score2, 100.0)

    def test_inbox_capture(self):
        entry = self.mgr.capture_inbox("Test agent discovery", author="qwen", tags=["qwen", "test"])
        self.assertTrue(entry["id"].startswith("SEED-"))
        self.assertEqual(entry["author"], "qwen")
        self.assertEqual(entry["idea"], "Test agent discovery")

        # Verify inbox file exists and contains the line
        inbox_file = self.temp_dir / "LEARNING" / "research" / "inbox.jsonl"
        self.assertTrue(inbox_file.exists())
        lines = inbox_file.read_text(encoding="utf-8").strip().splitlines()
        self.assertEqual(len(lines), 1)
        data = json.loads(lines[0])
        self.assertEqual(data["id"], entry["id"])

    def test_compile_and_list(self):
        # Create two sample missions
        m1 = {
            "id": "MISSION-001",
            "title": "Cloud Worker",
            "status": "STAGED",
            "scores": {
                "strategic_leverage": 5,
                "epistemic_depth": 4,
                "cost_weight": 0.1,
                "operational_friction": 2
            },
            "hypothesis": "Hypothesis 1",
            "falsification_criteria": "Gate 1",
            "execution_surface": "cloud-worker"
        }
        m2 = {
            "id": "MISSION-002",
            "title": "Offline Qwen",
            "status": "PROPOSED",
            "scores": {
                "strategic_leverage": 5,
                "epistemic_depth": 4,
                "cost_weight": 0.05,
                "operational_friction": 2
            },
            "hypothesis": "Hypothesis 2",
            "falsification_criteria": "Gate 2",
            "execution_surface": "local"
        }

        self.mgr.save_mission(m1)
        self.mgr.save_mission(m2)

        # Compile
        self.mgr.compile()

        # Check index.jsonl
        index_file = self.temp_dir / "LEARNING" / "research" / "index.jsonl"
        self.assertTrue(index_file.exists())
        index_lines = [json.loads(line) for line in index_file.read_text(encoding="utf-8").strip().splitlines()]
        self.assertEqual(len(index_lines), 2)
        # MISSION-002 should be rank #1 because score 200 > 100
        self.assertEqual(index_lines[0]["id"], "MISSION-002")
        self.assertEqual(index_lines[0]["rank"], 1)
        self.assertEqual(index_lines[0]["priority_score"], 200.0)
        self.assertEqual(index_lines[1]["id"], "MISSION-001")
        self.assertEqual(index_lines[1]["rank"], 2)

        # Check backlog.md
        md_file = self.temp_dir / "LEARNING" / "research" / "backlog.md"
        self.assertTrue(md_file.exists())
        content = md_file.read_text(encoding="utf-8")
        self.assertIn("THIS FILE IS AUTOMATICALLY GENERATED", content)
        self.assertIn("| **#1** | `MISSION-002`", content)
        self.assertIn("| **#2** | `MISSION-001`", content)

    def test_record_result(self):
        m = {
            "id": "MISSION-010",
            "title": "Trial Mission",
            "status": "ACTIVE",
            "scores": {
                "strategic_leverage": 4,
                "epistemic_depth": 4,
                "cost_weight": 1.0,
                "operational_friction": 1
            },
            "hypothesis": "Trial hypothesis",
            "falsification_criteria": "Trial gate",
            "execution_surface": "local"
        }
        self.mgr.save_mission(m)

        updated = self.mgr.record_result(
            "MISSION-010",
            verdict="CORROBORATED",
            evidence="Unit tests succeeded with 0 regressions",
            citation="PR #100",
            lessons=["Lesson A", "Lesson B"],
            agent="antigravity"
        )

        self.assertEqual(updated["status"], "RESOLVED")
        self.assertEqual(updated["verdict"], "CORROBORATED")
        self.assertEqual(len(updated["evidence"]), 1)
        self.assertEqual(updated["evidence"][0]["citation"], "PR #100")
        self.assertEqual(updated["lessons_learned"], ["Lesson A", "Lesson B"])


if __name__ == "__main__":
    unittest.main()
