class TestIndexEnrichment(unittest.TestCase):
    def test_hypothesis_brief_first_sentence_and_cap(self):
        import manage_backlog as mb
        self.assertEqual(mb.hypothesis_brief("First claim. Second claim."), "First claim.")
        self.assertEqual(mb.hypothesis_brief(""), "")
        long = mb.hypothesis_brief("x" * 500)
        self.assertEqual(len(long), 220)
        self.assertTrue(long.endswith("\u2026"))

    def test_index_item_keeps_legacy_fields_and_adds_triage_fields(self):
        import manage_backlog as mb
        m = {"id": "MISSION-009", "title": "T", "status": "PROPOSED", "priority_score": 1.0,
             "hypothesis": "A holds. B follows.", "tags": ["a", "b"], "updated_at": "2026-11-03T00:00:00Z",
             "model_routing": {"cheapest_viable_tier": "free-local", "recommended_model": "m"}}
        item = mb.build_index_item(3, m)
        for legacy in ("rank", "id", "title", "status", "priority_score", "execution_surface",
                       "cheapest_viable_tier", "recommended_model", "verdict", "path"):
            self.assertIn(legacy, item)
        self.assertEqual(item["hypothesis_brief"], "A holds.")
        self.assertEqual(item["tags"], ["a", "b"])
        self.assertEqual(item["rank"], 3)

    def test_unknown_mission_keys_do_not_break_index_item(self):
        import manage_backlog as mb
        m = {"id": "MISSION-026", "title": "T", "upstream_skill_dependencies": ["x"], "reference_doctrines": ["y"]}
        self.assertEqual(mb.build_index_item(1, m)["id"], "MISSION-026")


class TestProjectedImpactValidation(unittest.TestCase):
    def test_validate_projected_impact(self):
        import manage_backlog as mb
        self.assertEqual(mb.validate_projected_impact(None), [])
        self.assertEqual(mb.validate_projected_impact({"paths": ["a/b.py", "docs/"], "resources": ["p:1"], "shared_generated": []}), [])
        for bad in ("x", {}, {"paths": []}, {"paths": [""]}, {"paths": [1]}, {"paths": ["/abs"]}, {"paths": ["../up"]},
                    {"paths": ["a"], "resources": "no"}, {"paths": ["a"], "shared_generated": [1]}):
            self.assertTrue(mb.validate_projected_impact(bad), f"should reject {bad!r}")

    def test_manager_validate_reports_bad_declaration(self):
        root = Path(tempfile.mkdtemp())
        try:
            mdir = root / "LEARNING" / "missions"
            mdir.mkdir(parents=True)
            base = {"title": "t", "hypothesis": "h", "falsification_criteria": "f", "status": "PROPOSED",
                    "scores": {"strategic_leverage": 1, "epistemic_depth": 1, "cost_weight": 1.0, "operational_friction": 1}, "priority_score": 1.0}
            (mdir / "MISSION-901.json").write_text(json.dumps({**base, "id": "MISSION-901", "projected_impact": {"paths": ["/abs"]}}))
            (mdir / "MISSION-902.json").write_text(json.dumps({**base, "id": "MISSION-902", "projected_impact": {"paths": ["a/b.py"]}}))
            errors = BacklogManager(root).validate()
            self.assertTrue(any("MISSION-901" in e and "projected_impact" in e for e in errors), errors)
            self.assertFalse(any("MISSION-902" in e for e in errors), errors)
        finally:
            shutil.rmtree(root, ignore_errors=True)


    def test_manager_validate_applies_the_json_schema_when_the_root_has_one(self):
        repo = Path(__file__).resolve().parents[6]
        root = Path(tempfile.mkdtemp())
        try:
            res = root / "LEARNING"
            (res / "missions").mkdir(parents=True)
            shutil.copy(repo / "LEARNING" / "missions" / "mission.schema.json", res / "missions" / "mission.schema.json")
            good = json.loads((repo / "LEARNING" / "missions" / "MISSION-034.json").read_text())
            bad = {**good, "id": "MISSION-902", "status": "DONE"}
            (res / "missions" / "MISSION-034.json").write_text(json.dumps(good))
            (res / "missions" / "MISSION-902.json").write_text(json.dumps(bad))
            errors = BacklogManager(root).validate()
            self.assertTrue(any("MISSION-902" in e and "status" in e for e in errors), errors)
            self.assertFalse(any("MISSION-034" in e for e in errors), errors)
        finally:
            shutil.rmtree(root, ignore_errors=True)

    def test_repo_manifests_pass_both_the_schema_and_the_invariants(self):
        repo = Path(__file__).resolve().parents[6]
        self.assertEqual(BacklogManager(repo).validate(), [])


def _m(mid, title, hyp, tags=(), related=None):
    return {"id": mid, "title": title, "hypothesis": hyp, "tags": list(tags),
            "status": "PROPOSED", "related_missions": related or {}}


class TestRelatedMissions(unittest.TestCase):
    def setUp(self):
        self.corpus = [
            _m("MISSION-001", "Quota window telemetry for model routing",
               "Measure token usage per backend to improve model routing decisions.", ["routing", "tokens"]),
            _m("MISSION-002", "Failover routing across subscriptions",
               "Route requests across subscription backends when a token quota is exhausted.", ["routing"]),
            _m("MISSION-003", "Chronicle formatting cleanup",
               "Normalise markdown headings in chronicle entries.", ["docs"]),
            _m("MISSION-004", "Image thumbnail generation",
               "Generate thumbnails for archived screenshots.", ["media"]),
        ]

    def test_ranks_similar_first_and_excludes_self(self):
        out = related_missions(self.corpus, target_id="MISSION-001", top=3)
        ids = [r["id"] for r in out]
        self.assertNotIn("MISSION-001", ids)
        self.assertEqual(ids[0], "MISSION-002")
        self.assertEqual(sorted((r["score"] for r in out), reverse=True), [r["score"] for r in out])

    def test_shared_terms_reported(self):
        out = related_missions(self.corpus, target_id="MISSION-001", top=1)
        self.assertTrue({"routing", "token"} & set(out[0]["shared_terms"]))

    def test_link_state_unlinked_one_way_and_mutual(self):
        out = {r["id"]: r["link"] for r in related_missions(self.corpus, target_id="MISSION-001", top=3)}
        self.assertEqual(out["MISSION-002"], "unlinked")
        self.corpus[0]["related_missions"] = {"MISSION-002": "x"}
        out = {r["id"]: r["link"] for r in related_missions(self.corpus, target_id="MISSION-001", top=3)}
        self.assertEqual(out["MISSION-002"], "one-way")
        self.corpus[1]["related_missions"] = {"MISSION-001": "y"}
        out = {r["id"]: r["link"] for r in related_missions(self.corpus, target_id="MISSION-001", top=3)}
        self.assertEqual(out["MISSION-002"], "linked")

    def test_text_mode_for_undrafted_idea(self):
        out = related_missions(self.corpus, text="failover across subscription backends when token quota is exhausted", top=2)
        self.assertEqual(out[0]["id"], "MISSION-002")

    def test_unknown_target_raises(self):
        with self.assertRaises(KeyError):
            related_missions(self.corpus, target_id="MISSION-999")

    def test_zero_overlap_scores_zero_and_is_omitted(self):
        out = related_missions(self.corpus, target_id="MISSION-004", top=5)
        self.assertEqual(out, [])
